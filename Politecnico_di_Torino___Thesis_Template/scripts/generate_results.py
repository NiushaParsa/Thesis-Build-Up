SOURCES = {}


def read(relative, lines=False):
    path = REPO / relative
    raw = path.read_bytes()
    SOURCES[relative] = hashlib.sha256(raw).hexdigest()
    text = raw.decode("utf-8-sig")
    return [json.loads(x) for x in text.splitlines() if x.strip()] if lines else json.loads(text)


def tex(value):
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}"}
    return "".join(replacements.get(c, c) for c in str(value))


def table(name, caption, label, columns, header, rows, note=""):
    result = [r"% Generated by scripts/generate_results.py; do not hand-edit.",
              r"\begin{table}[htbp]", r"\centering\small",
              r"\caption{" + caption + "}", r"\label{" + label + "}",
              r"\begin{tabular}{" + columns + "}", r"\toprule",
              " & ".join(header) + r"\\", r"\midrule"]
    result += [" & ".join(row) + r"\\" for row in rows]
    result += [r"\bottomrule", r"\end{tabular}"]
    if note:
        result += [r"\par\smallskip\begin{minipage}{\textwidth}\footnotesize " + note + r"\end{minipage}"]
    result += [r"\end{table}", ""]
    (TABLES / f"{name}.tex").write_text("\n".join(result), encoding="utf-8")


